package com.inazumastation.app;

public class MoveData {
    public String name = "";
    public String element = "";
    public String type = "";
    public String cost = "";
    public String power = "";

    public MoveData(String name, String element, String type, String cost, String power) {
        this.name = name;
        this.element = element;
        this.type = type;
        this.cost = cost;
        this.power = power;
    }
}